import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn, spawnSync } from 'node:child_process';
import net from 'node:net';
const root=path.resolve(import.meta.dirname,'..');
const dataRoot=fs.mkdtempSync(path.join(os.tmpdir(),'fleet-ui-'));
const python=process.env.FLEET_PYTHON||'python';
const prepared=spawnSync(python,[path.join(root,'tests/prepare_ui.py'),dataRoot],{cwd:root,windowsHide:true,encoding:'utf8'});
assert.equal(prepared.status,0,prepared.stderr);
const fixture=JSON.parse(fs.readFileSync(path.join(dataRoot,'fixture.json'),'utf8'));
const lease=net.createServer();await new Promise(r=>lease.listen(0,'127.0.0.1',r));const port=lease.address().port;await new Promise(r=>lease.close(r));
const url='http://127.0.0.1:'+port;
const server=spawn(python,[path.join(root,'fleet_studio.py'),'--data-root',dataRoot,'--port',String(port),'--no-launch','--backlog-fixture',path.join(dataRoot,'issues.json')],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});
let serverOutput='';server.stderr.on('data',x=>serverOutput+=x);let browser;const errors=[];const checks=[];
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function until(test,message){const deadline=Date.now()+15000;while(Date.now()<deadline){if(await test())return;await sleep(100);}throw new Error(message+' '+serverOutput);}
try{
 await until(async()=>{try{return (await fetch(url+'/api/health')).ok;}catch{return false;}},'Server failed to start');
 browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:1050}});page.on('pageerror',e=>errors.push(e.message));
 const bootstrap=async()=>await (await fetch(url+'/api/bootstrap')).json();
 const initial=await bootstrap();const token=initial.token;
 const post=async(endpoint,body)=>{const r=await fetch(url+endpoint,{method:'POST',headers:{'Content-Type':'application/json','X-Fleet-Token':token},body:JSON.stringify(body)});const d=await r.json();assert.ok(r.ok,JSON.stringify(d));return d;};
 await page.goto(url);await page.locator('.progress-metrics').waitFor();
 await until(async()=>(await page.locator('.progress-attention-list').innerText()).includes('Waiting for reviewed input'),'Missing blocker');
 assert.equal(await page.locator('#fleet-title').innerText(),'Progress');
 assert.match(await page.locator('.progress-metrics').innerText(),/Awaiting handoff receipt/);
 await page.locator('[data-progress-tab="agents"]').click();
 await page.locator('[data-progress-agent="'+fixture.writerId+'"]').click();
 await page.locator('#progress-detail').waitFor({state:'visible'});
 assert.match(await page.locator('#progress-detail-body').innerText(),/Coordinator supplies the input contract/);
 assert.match(await page.locator('#progress-detail-body').innerText(),/<script>/);
 assert.equal(await page.evaluate(()=>window.injected),undefined);
 await page.locator('#close-progress-detail').click();
 checks.push('Default progress dashboard combines tracker, report, blocker and session observations; report text is escaped');
 await page.locator('[data-progress-tab="handoffs"]').click();
 assert.match(await page.locator('#content').innerText(),/No agent receipt/);
 await page.locator('[data-progress-handoff="synthetic-handoff"]').click();
 assert.match(await page.locator('#progress-detail-body').innerText(),/queued/);
 await page.locator('[data-progress-edit-link]').click();
 await page.locator('#editor').waitFor({state:'visible'});
 assert.equal((await bootstrap()).state.revision,initial.state.revision,'Inspecting a handoff cannot change the workflow');
 await page.locator('#cancel-editor').click();
 await page.locator('#nav-progress').click();
 await page.locator('#progress-settings').click();
 await page.locator('#progress-handoffMinutes').fill('45');
 await page.locator('#progress-settings-form button[type="submit"]').click();
 await until(async()=>((await bootstrap()).state.fleets[0].progress||{}).handoffMinutes===45,'Settings did not save');
 checks.push('Handoff investigation opens its draft contract; monitoring thresholds persist');
 await page.locator('[data-progress-tab="workflow"]').click();
 await page.locator('.progress-role').first().waitFor();
 assert.equal(await page.locator('.progress-role').count(),3);
 await page.locator('.progress-role').first().click();
 assert.match(await page.locator('#progress-detail-body').innerText(),/Communication contracts/);
 await page.locator('#close-progress-detail').click();
 await page.locator('#nav-workflow').click();
 await page.locator('[data-workflow-section="policies"]').click();
 await page.locator('[data-workflow-edit="progress-reporting"]').click();
 await page.locator('#wf-text').fill('Report meaningful task boundaries with evidence links.');
 await page.locator('#workflow-item-form button[type="submit"]').click();
 await page.locator('#workflow-item-editor').waitFor({state:'hidden'});
 await page.locator('#workflow-deploy').click();await page.locator('#workflow-review').waitFor({state:'visible'});
 await page.locator('#workflow-review-body details').first().locator('summary').click();
 assert.match(await page.locator('#workflow-review-body').innerText(),/progress-reporting/);
 await page.locator('#workflow-apply').click();await page.locator('#workflow-review').waitFor({state:'hidden'});
 await page.locator('#nav-progress').click();await page.evaluate(()=>loadProgress(true));
 assert.match(await page.locator('.progress-release').innerText(),/0\/3 agents acknowledged/);
 checks.push('Deployed graph links roles and contracts; reviewed deployment resets adoption');
 const current=await bootstrap();const inspect=await post('/api/workflow/inspect',{fleetId:fixture.fleetId});
 const recipient=current.state.fleets[0].agents.find(a=>a.id===fixture.integratorId);
 await post('/api/progress/report',{...fixture.payload,agentId:recipient.id,sessionId:recipient.sessionId,releaseId:inspect.active.id,eventId:'received-101',kind:'handoff-received',handoffId:'synthetic-handoff',reason:'',nextAction:''});
 await page.evaluate(()=>loadProgress(true));await page.locator('[data-progress-tab="handoffs"]').click();
 assert.match(await page.locator('#content').innerText(),/Agent received/);
 assert.match(await page.locator('#content').innerText(),/queued/);
 checks.push('Agent receipt is displayed independently of queue delivery and tracker completion');
 await page.route('**/api/progress?**',async route=>{const response=await route.fetch();const data=await response.json();data.tracker.stale=true;data.tracker.error='Synthetic tracker outage';await route.fulfill({response,json:data});});
 await page.evaluate(()=>loadProgress(true));assert.match(await page.locator('.backlog-notice').innerText(),/Synthetic tracker outage/);
 await page.unroute('**/api/progress?**');await page.evaluate(()=>loadProgress(true));
 await page.locator('[data-progress-tab="attention"]').click();
 const metrics=await page.locator('.progress-metrics').boundingBox(),tabs=await page.locator('.progress-tabs').boundingBox();
 assert.ok(tabs.y>=metrics.y+metrics.height,'Tabs must be below the metric grid');
 await page.screenshot({path:path.join(root,'tests/progress.png'),fullPage:true});
 await page.setViewportSize({width:720,height:1000});await page.screenshot({path:path.join(root,'tests/progress-mobile.png'),fullPage:true});
 await page.reload();await page.locator('.progress-metrics').waitFor();
 assert.deepEqual(errors,[]);assert.equal((await bootstrap()).status.controls.length,0,'Tests must never send to agents');
 checks.push('Outage labels, reload and narrow layout; no native agent controls invoked');
 console.log(JSON.stringify({passed:true,checks},null,2));
}finally{
 if(browser)await browser.close();
 server.kill();await new Promise(r=>server.once('exit',r));
 // Only this test-created temporary directory is removed.
 assert.ok(path.resolve(dataRoot).startsWith(path.resolve(os.tmpdir())+path.sep));
 assert.ok(path.basename(dataRoot).startsWith('fleet-ui-'));
 fs.rmSync(dataRoot,{recursive:true,force:true});
}
